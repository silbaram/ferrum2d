import assert from "node:assert/strict";
import {mkdir, writeFile} from "node:fs/promises";
import {encodePngRgba} from "../../scripts/tools/pack-textures.mjs";
import {showPlacementBottom, showPlacementAssetPanel, clickPlacementToolAction, inspectPlacementAsset, choosePlacementAsset} from "./placement-panel-navigation.mjs";

export async function smokePlacementToolUi(parent, mode = "2d", timeoutMs = 30000) {
  const output = "artifacts/editor-ux-modernization"; await mkdir(output, {recursive:true});
  const page = await parent.context().browser().newPage({viewport:{width:1440,height:960},deviceScaleFactor:mode==="spatial"?2:1});
  const errors=[]; page.on("pageerror", error=>errors.push(error.message));
  let generatorRequests=0;
  try {
    const url=new URL(parent.url()); url.search=mode==="spatial"?"?scene=hd2d":"";
    await page.goto(url.href,{waitUntil:"networkidle"});
    await page.waitForFunction(mode=>window.ferrumPlacementWorkspaceMode===mode&&window.ferrumPlacementViewerRuntimeFrame?.drawCalls>0,mode,{timeout:timeoutMs});
    await page.locator('[data-placement-language]').selectOption('en');
    const evidence=()=>page.evaluate(()=>JSON.stringify({source:window.ferrumPlacementSpatialExportDocument(),patch:window.ferrumPlacementViewerExportPatch(),history:window.ferrumPlacementViewerHistory,selected:window.ferrumPlacementViewerState.selectedInstanceIds,tabs:window.ferrumPlacementWorkspaceDocuments}));
    const before=await evidence(); await showPlacementBottom(page);
    const density=[];
    for(const [kind,baseline] of [['normal',8],['aseprite',16],['tile',10]]){
      const tool=page.locator(`[data-placement-${kind}-tool]`);
      await showPlacementAssetPanel(page,kind);
      await tool.scrollIntoViewIfNeeded();
      const count=await tool.evaluate(node=>[...node.querySelectorAll('button')].filter(button=>button.getClientRects().length>0&&!button.closest('details:not([open])')).length);
      assert(count<baseline,`${kind} visible actions (${count}) must be fewer than baseline (${baseline})`);
      assert(await tool.locator('[data-placement-tool-action-menu]').isVisible());
      density.push({kind,baseline,visibleButtons:count,comparison:'initial empty tool · same button visibility rule'});
      await page.locator('[data-placement-asset-view-back]').click();
    }
    const browser=page.locator('[data-placement-asset-browser]'),card=browser.locator('[data-placement-browser-asset="sprite:crate"]');
    await inspectPlacementAsset(page,card);
    assert.match(await browser.locator('[data-placement-asset-detail]').innerText(),/crate/i);
    assert.equal(await evidence(),before,'Inspecting assets must not select scene objects or edit documents');
    assert(await page.locator('[data-placement-tool-cancel]').isHidden(),'Inspection alone must not arm placement');
    assert.equal(await browser.locator('.placement-asset-cell [data-placement-edit-pixels]').count(),0,'Actions belong to the selected asset detail');
    await browser.locator('[data-placement-asset-view]').selectOption('list');
    assert.equal(await browser.getAttribute('data-asset-view'),'list');
    await card.focus();await page.keyboard.press('ArrowRight');
    assert.equal(await browser.locator('[data-placement-browser-asset][aria-pressed=true]').count(),1);
    await inspectPlacementAsset(page,card);
    await browser.locator('[data-placement-asset-usage-open]').click();
    const usage=page.locator('[data-placement-asset-usage]');
    assert.equal(await usage.evaluate(n=>n.open),true);
    await usage.locator('[data-placement-usage-clear-filter]').waitFor({state:'visible'});
    await usage.locator('[data-placement-usage-clear-filter]').click();
    await page.locator('[data-placement-asset-view-back]').click();
    const normal=page.locator('[data-placement-normal-tool]'); await showPlacementAssetPanel(page,'normal');
    assert(await normal.locator('[data-normal-action=generate]').isVisible());
    assert(await normal.locator('[data-normal-action=generate]').isDisabled());
    assert.match(await normal.locator('.placement-tool-reason').innerText(),/source image/);
    const advanced=normal.locator('[data-normal-advanced]');
    assert.equal(await advanced.evaluate(n=>n.open),false);
    await advanced.locator(':scope > summary').click();
    await normal.getByLabel('Detail Strength',{exact:true}).fill('2');
    await normal.getByLabel('Detail Strength',{exact:true}).press('Tab');
    const pixels=new Uint8Array(2*2*4); pixels.fill(255);
    await normal.getByLabel('Normal source image',{exact:true}).setInputFiles({name:'ui-source.png',mimeType:'image/png',buffer:encodePngRgba(2,2,pixels)});
    await page.waitForFunction(()=>document.querySelector('[data-normal-source]').textContent.includes('ui-source.png')&&document.querySelector('[data-placement-normal-tool]').dataset.normalBusy==='false');
    const strength=normal.getByLabel('Normal Strength',{exact:true}); await strength.fill('-1'); await strength.press('Tab');
    await page.route('**/__ferrum-normal-generator/config.json',route=>{generatorRequests++;return route.fulfill({status:503,body:'test unavailable'});});
    await normal.locator('[data-normal-action=generate]').click();
    assert.equal(await strength.getAttribute('aria-invalid'),'true');
    const feedbackId=await strength.getAttribute('aria-describedby'); assert(await page.locator('#'+feedbackId).isVisible());
    assert.match(await page.locator('#'+feedbackId).innerText(),/0.*8/); assert.equal(generatorRequests,0);
    assert.equal(await normal.locator('[data-normal-status]').getAttribute('role'),'alert');
    await page.setViewportSize({width:390,height:844});await showPlacementBottom(page);await strength.scrollIntoViewIfNeeded();
    assert(await strength.evaluate(input=>input.closest('label').scrollWidth<=input.closest('label').clientWidth+1),'Inline input errors must wrap inside narrow tool rows');
    await page.setViewportSize({width:1440,height:960});
    await strength.fill('0.15'); await strength.press('Tab'); assert.equal(await strength.getAttribute('aria-invalid'),null);
    await normal.locator('[data-normal-action=generate]').click();
    await page.waitForFunction(()=>document.querySelector('[data-normal-status]').textContent.includes('Generation failed'));
    assert.equal(generatorRequests,1,'Valid sub-step precision reaches the existing generator owner');
    await clickPlacementToolAction(page,normal.locator('[data-normal-action=expand]'));
    await clickPlacementToolAction(page,normal.locator('[data-normal-action=expand]'));
    const menu=normal.locator('[data-placement-tool-action-menu=normal]');
    await menu.locator(':scope > summary').click();
    assert(await menu.locator('.placement-tool-action-note').filter({hasText:'No generation is running'}).isVisible());
    await menu.locator(':scope > summary').press('ArrowDown');
    assert(await menu.locator('.placement-control-panel').evaluate(node=>node===document.activeElement),'All-disabled action menus still expose a keyboard-readable panel');
    assert.equal(await menu.evaluate(n=>n.open),true); await page.keyboard.press('Escape');
    assert.equal(await menu.evaluate(n=>n.open),false);
    assert(await menu.locator(':scope > summary').evaluate(n=>n===document.activeElement));
    await page.locator('[data-placement-language]').selectOption('ko');
    const viewports=[];
    for(const [width,height] of [[1600,1000],[1280,720],[860,720],[390,844]]){
      await page.setViewportSize({width,height});await inspectPlacementAsset(page,card);
      assert(await browser.locator('[data-placement-asset-place]').isVisible());
      assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
      assert.equal(await evidence(),before,'Viewport changes and asset detail inspection are view only');
      viewports.push({width,height});
    }
    await page.setViewportSize({width:1440,height:960});
    assert.match(await normal.locator('.placement-tool-scope').innerText(),/프로젝트/);
    await page.screenshot({path:`${output}/ux01-${mode}.png`,fullPage:true});
    assert.equal(await evidence(),before,'Tool configuration, validation and failed generation must preserve scene/patch/history/selection/tabs');
    assert.deepEqual(errors,[]);
    await page.locator('[data-placement-language]').selectOption('en');
    const importer=page.locator('[data-placement-aseprite-tool]');
    await showPlacementAssetPanel(page,'aseprite');
    await importer.getByRole('tab',{name:'Source',exact:true}).click();
    assert(await importer.locator('[data-aseprite-action=inspect]').isDisabled());
    assert.match(await importer.locator('.placement-tool-reason').innerText(),/JSON and PNG/);
    await importer.getByLabel('Aseprite JSON',{exact:true}).setInputFiles({name:'invalid-source.json',mimeType:'application/json',buffer:Buffer.from('{ invalid')});
    await importer.getByLabel('Aseprite PNG',{exact:true}).setInputFiles({name:'invalid-source.png',mimeType:'image/png',buffer:encodePngRgba(2,2,pixels)});
    await clickPlacementToolAction(importer.locator('[data-aseprite-action=inspect]'));
    await page.waitForFunction(()=>document.querySelector('[data-placement-aseprite-tool]').dataset.asepriteBusy==='false'&&document.querySelector('[data-placement-import-diagnostics=aseprite]').hidden===false);
    const diagnostics=importer.locator('[data-placement-import-diagnostics=aseprite]');
    assert(await diagnostics.locator('.placement-import-problem-summary').isVisible());
    assert.match(await diagnostics.locator('.placement-import-problem-summary').innerText(),/invalid-source.json/);
    assert(await diagnostics.locator('details pre').isHidden(),'Technical payload is disclosed after the readable recovery summary');
    const raw=JSON.parse(await diagnostics.locator('pre').textContent());assert.equal(raw[0].source.file,'invalid-source.json');
    await diagnostics.locator('details > summary').click();assert(await diagnostics.locator('pre').isVisible());
    await importer.getByLabel('Aseprite asset name',{exact:true}).fill('corrected-source');
    assert(await diagnostics.isHidden(),'Changing source must clear stale failure evidence');
    assert.equal(await evidence(),before,'Import failure and correction must preserve the document and undo history');
    await page.locator('[data-placement-language]').selectOption('ko');
    await page.setViewportSize({width:390,height:844});await showPlacementBottom(page);
    await inspectPlacementAsset(page,card);assert(await browser.locator('.placement-asset-back').isVisible());
    assert(await card.isHidden());await browser.locator('.placement-asset-back').click();assert(await card.isVisible());
    await page.screenshot({path:`${output}/ux02-compact-${mode}.png`,fullPage:true});
    await page.setViewportSize({width:1440,height:960});await choosePlacementAsset(page,card);
    assert(await page.locator('[data-placement-tool-cancel]').isVisible(),'Explicit placement retains the existing tool owner');
    await page.keyboard.press('Escape');
    const result={ok:true,mode,density,viewports,assets:{inspectPreservesScene:true,explicitPlace:true,listView:true,keyboard:true,usageLink:true,compact:true},normal:{advanced:true,primaryOverflow:true,disabledReason:true,inlineValidation:true,precisionPreserved:true,focusReturn:true,readonly:true},imports:{missingSourceReason:true,readableFailure:true,rawEvidencePreserved:true,sourceChangeClearsFailure:true},pageErrors:errors};
    await writeFile(`${output}/tool-ui-${mode}.json`,JSON.stringify(result,null,2)+'\n'); return result;
  } catch(error) {
    await page.screenshot({path:`${output}/failure-${mode}.png`,fullPage:true});throw error;
  } finally {await page.close();}
}
