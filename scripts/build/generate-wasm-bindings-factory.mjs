export function renderFactory(source) {
  assert(!/^import\s/m.test(source), "unexpected generated import");
  const names=[];
  let body=source.replace(/^export (class|const|function) (\w+)/gm,(_,kind,name)=>{names.push(name);return `${kind} ${name}`;});
  assert.deepEqual(names,expectedExports,"unknown or missing generated exports: review the factory generator");
  const tail="export { initSync, __wbg_init as default };";
  assert.equal(body.split(tail).length,2,"unexpected generated export tail");body=body.replace(tail,"");assert(!/^export\s/m.test(body));
  assert.equal(body.split("function initSync(module) {").length,2);body=body.replace("function initSync(module) {","function __factory_initSync(module) {");
  assert.equal(body.split("async function __wbg_init(module_or_path) {").length,2);body=body.replace("async function __wbg_init(module_or_path) {","async function __factory_init(module_or_path) {");
  assert.equal(body.split("function __wbg_finalize_init(instance, module) {").length,2);
  body=body.replace("function __wbg_finalize_init(instance, module) {","function __wbg_finalize_init(instance, module) {\n    if (factoryState !== 'initializing') throw new Error('Wasm namespace initialization cancelled');");
  let finalizers=0;
  body=body.replace(/\(typeof FinalizationRegistry === 'undefined'\)\s*\? \{ register: \(\) => \{\}, unregister: \(\) => \{\} \}\s*: new FinalizationRegistry\(ptr => wasm\.(\w+)\(ptr, 1\)\)/g,(_,free)=>{finalizers++;return `makeFinalizer('${free}')`;});
  assert.equal(finalizers,6,"unexpected generated finalizer scaffolding");
  for(const name of caches)assert(body.includes(`let ${name} = null;`),`missing cache ${name}`);
  const sourceHash=createHash("sha256").update(source).digest("hex");
  return `// Generated by generate-wasm-bindings-factory.mjs; source SHA256 ${sourceHash}.
// Each call owns its bindings, native pointers, imports, caches and finalizers.
export function createFerrumWasmBindings(options = {}) {
let factoryState = 'new', inputIdentity, initialization;
let finalizersRun = 0, finalizersSuppressed = 0, finalizerFailures = 0;
function clearNativeReferences() {
  wasm = undefined; wasmInstance = undefined; wasmModule = undefined;
  ${caches.map(n=>`${n} = null;`).join("\n  ")}
  inputIdentity = undefined; initialization = undefined; WASM_VECTOR_LEN = 0;
}
function poison() { if (factoryState !== 'disposed') factoryState = 'poisoned'; clearNativeReferences(); }
function assertReady() { if (factoryState !== 'ready') throw new Error('Wasm namespace is ' + factoryState); }
function makeFinalizer(free) {
  const callback = pointer => {
    if (factoryState !== 'ready') { finalizersSuppressed++; return; }
    finalizersRun++;
    try { wasm[free](pointer, 1); }
    catch { finalizerFailures++; poison(); }
  };
  if (options.finalizationRegistryFactory) return options.finalizationRegistryFactory(callback);
  return typeof FinalizationRegistry === 'undefined'
    ? { register() {}, unregister() {} } : new FinalizationRegistry(callback);
}
function identity(input) {
  if (input !== null && typeof input === 'object' && Object.getPrototypeOf(input) === Object.prototype)
    return 'module' in input ? input.module : input.module_or_path;
  return input;
}
function reuse(input) {
  if (factoryState === 'disposed' || factoryState === 'poisoned') throw new Error('Wasm namespace is ' + factoryState);
  if (factoryState !== 'new' && inputIdentity !== identity(input)) throw new Error('Wasm namespace initialized with different input');
}
function initSync(input) {
  reuse(input);
  if (factoryState === 'ready') return wasm;
  if (factoryState === 'initializing') throw new Error('Wasm namespace initialization already pending');
  inputIdentity = identity(input); factoryState = 'initializing';
  try { const result = __factory_initSync(input); factoryState = 'ready'; return result; }
  catch (error) { poison(); throw error; }
}
function init(input) {
  try { reuse(input); } catch (error) { return Promise.reject(error); }
  if (factoryState === 'ready') return Promise.resolve(wasm);
  if (factoryState === 'initializing') return initialization;
  inputIdentity = identity(input); factoryState = 'initializing';
  initialization = Promise.resolve().then(() => {
    if (factoryState !== 'initializing') throw new Error('Wasm namespace initialization cancelled');
    return __factory_init(input);
  }).then(result => {
    if (factoryState !== 'initializing') throw new Error('Wasm namespace initialization cancelled');
    factoryState = 'ready'; return result;
  }, error => { poison(); throw error; });
  return initialization;
}
${body}
const bindings = Object.freeze({ ${names.join(", ")}, initSync, default: init });
return Object.freeze({ bindings,
  invoke(operation) { assertReady(); try { return operation(bindings); }
    catch (error) { if (error instanceof WebAssembly.RuntimeError) poison(); throw error; } },
  dispose() { factoryState = 'disposed'; clearNativeReferences(); },
  state() { return Object.freeze({ state: factoryState, finalizersRun, finalizersSuppressed, finalizerFailures,
    retainsInstance: wasmInstance !== undefined, retainsModule: wasmModule !== undefined, retainsWasm: wasm !== undefined,
    retainedViewCaches: [${caches.join(",")}].filter(v => v !== null).length }); }
});
}
`;
}
export async function generateWasmBindingsFactory(pkgRoot,{check=false}={}) {
  if (pkgRoot instanceof URL) pkgRoot=fileURLToPath(pkgRoot);
  const source=await readFile(path.join(pkgRoot,"ferrum_core.js"),"utf8");
  const outputs={"ferrum_core_factory.js":renderFactory(source),"ferrum_core_factory.d.ts":types};
  for(const [name,content] of Object.entries(outputs)) {
    const target=path.join(pkgRoot,name);
    if(check) assert.equal(await readFile(target,"utf8"),content,`${name} is stale; regenerate Wasm bindings factory`);
    else await writeFile(target,content);
  }
}
if(process.argv[1] && path.resolve(process.argv[1])===fileURLToPath(import.meta.url)) {
  const args=process.argv.slice(2);assert(args.every(a=>a==='--check'),"unknown generator argument");
  await generateWasmBindingsFactory(fileURLToPath(new URL("../../packages/ferrum-web/pkg/",import.meta.url)),{check:args.includes('--check')});
}
