#!/usr/bin/env node
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const generated = "packages/ferrum-web/src/nativeFileSdkBuild.ts";
const fixedInputs = [
  "packages/ferrum-web/package.json",
  "packages/ferrum-web/tsconfig.json",
  "packages/ferrum-web/pkg/ferrum_core.js",
  "packages/ferrum-web/pkg/ferrum_core_factory.js",
  "scripts/build/fix-dist-esm-extensions.mjs",
];

/** Strict same-build compatibility identity, not a signature or migration key.
 * Paths and bytes are length-prefixed; filesystem order and the generated file
 * itself do not affect the hash. Test files are not runtime build inputs. */
export function renderNativeFileSdkBuild(inputs) {
  const hash = createHash("sha256");
  hash.update("ferrum-native-file-sdk-build-v1\0");
  for (const [name, bytes] of [...inputs].sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0)) {
    const key = Buffer.from(name, "utf8"), size = Buffer.alloc(8);
    size.writeUInt32LE(key.length, 0); size.writeUInt32LE(bytes.length, 4);
    hash.update(size); hash.update(key); hash.update(bytes);
  }
  const digest = hash.digest();
  return `// Generated by generate-native-file-sdk-build.mjs; do not edit.
// Strict compatibility identity only; SHA256 ${digest.toString("hex")}.
export const NATIVE_FILE_SDK_BUILD: readonly [number, number] = Object.freeze([${digest.readUInt32LE(0)}, ${digest.readUInt32LE(4)}]);
`;
}

export async function generateNativeFileSdkBuild(root, { check = false, checkDist = false } = {}) {
  const files = [...fixedInputs];
  async function visit(relative) {
    for (const entry of await readdir(path.join(root, relative), { withFileTypes: true })) {
      const name = `${relative}/${entry.name}`;
      if (entry.isDirectory()) await visit(name);
      else if (entry.isFile() && name.endsWith(".ts") && name !== generated) files.push(name);
    }
  }
  await visit("packages/ferrum-web/src");
  const inputs = await Promise.all(files.map(async name => [name, await readFile(path.join(root, name))]));
  const expected = renderNativeFileSdkBuild(inputs), target = path.join(root, generated);
  let actual;
  try { actual = await readFile(target, "utf8"); }
  catch (error) { if (error.code !== "ENOENT") throw error; }
  if (check) assert.equal(actual, expected, "Native-file SDK build identity is stale; build ferrum-web again");
  else if (actual !== expected) await writeFile(target, expected);
  if (checkDist) {
    const output = await readFile(path.join(root, "packages/ferrum-web/dist/nativeFileSdkBuild.js"), "utf8");
    assert.equal(output, expected.replace(": readonly [number, number]", ""),
      "Packed native-file SDK build identity is stale; build ferrum-web again");
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  assert(args.every(arg => arg === "--check"), "unknown SDK build identity generator argument");
  await generateNativeFileSdkBuild(fileURLToPath(new URL("../../", import.meta.url)), { check: args.includes("--check") });
}
